// First-visit default is English so a public visitor never lands on a Spanish
// UI just because the author wrote the source comments in Spanish. The stored
// value (from a previous session, or applied later by /api/panel/settings)
// always wins over this default.
window.AppI18n = {
  lang: localStorage.getItem('ac-lang') || 'en',
  setLang(l) {
    if (dict[l]) {
      this.lang = l;
      localStorage.setItem('ac-lang', l);
      try { document.documentElement.lang = l; } catch {}
      window.dispatchEvent(new Event('ac-lang-change'));
    }
  },
  t(key, params = {}) {
    let str = dict[this.lang]?.[key] || key;
    for (const [k, v] of Object.entries(params)) {
      // replaceAll (vs replace) so a translator can use the same placeholder
      // twice in a sentence ("…{name}… {name}…") without silently keeping the
      // second occurrence as a literal. Cast v to a string so numeric values
      // (mb, count, …) render correctly without coercion side-effects.
      str = str.split(`{${k}}`).join(String(v));
    }
    return str;
  }
};

